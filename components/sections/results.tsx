"use client";

import React, { useState, useEffect } from "react";
import { Container } from "@/components/ui/container";
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Button } from "@/components/ui/button";

interface ResultsProps {
  roiBudget: string;
  setRoiBudget: (budget: string) => void;
}

export function Results({ roiBudget, setRoiBudget }: ResultsProps) {
  const [estimatedMonthly, setEstimatedMonthly] = useState<number | null>(null);
  const [estimatedAnnual, setEstimatedAnnual] = useState<number | null>(null);

  const calculateRoi = (e?: React.FormEvent) => {
    e?.preventDefault();
    const budget = parseFloat(roiBudget);
    if (!isNaN(budget) && budget > 0) {
      setEstimatedMonthly(budget * 3);
      setEstimatedAnnual(budget * 3 * 12);
    }
  };

  useEffect(() => {
    calculateRoi();
  }, [roiBudget]);

  return (
    <section id="calculator" className="py-20">
      <Container className="max-w-4xl">
        <Card className="p-8 shadow-xl">
          <CardHeader className="p-0 mb-6">
            <CardTitle className="text-2xl font-extrabold">Estimate Your Growth ROI</CardTitle>
            <CardDescription className="text-slate-500">
              Enter your projected monthly acquisition budget to estimate potential revenue generated by our campaigns.
            </CardDescription>
          </CardHeader>

          <CardContent className="p-0">
            <form onSubmit={calculateRoi} className="space-y-4">
              <div>
                <label htmlFor="budget-input" className="block text-xs font-bold uppercase text-slate-400 mb-2">
                  Monthly Advertising Budget (₹)
                </label>
                <Input
                  id="budget-input"
                  type="number"
                  value={roiBudget}
                  onChange={(e) => setRoiBudget(e.target.value)}
                  placeholder="50000"
                  required
                />
              </div>

              <Button
                type="submit"
                className="w-full py-3 font-semibold"
              >
                Compute Estimated Returns
              </Button>
            </form>

            {estimatedMonthly !== null && estimatedAnnual !== null && (
              <div className="mt-6 space-y-4 p-6 rounded-lg bg-blue-500/10 border border-blue-500/20">
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 text-center">
                  <div>
                    <p className="text-xs text-slate-500 font-semibold">Estimated ROAS</p>
                    <p className="text-xl font-bold text-blue-600 mt-1">3.0x</p>
                  </div>
                  <div>
                    <p className="text-xs text-slate-500 font-semibold">Est. Monthly Revenue</p>
                    <p className="text-xl font-bold text-blue-600 font-mono mt-1">₹{estimatedMonthly.toLocaleString()}</p>
                  </div>
                  <div>
                    <p className="text-xs text-slate-500 font-semibold">Est. Annual Revenue</p>
                    <p className="text-xl font-bold text-blue-600 font-mono mt-1">₹{estimatedAnnual.toLocaleString()}</p>
                  </div>
                </div>
                <div className="pt-3 border-t border-blue-500/20 text-center">
                  <p className="text-[10px] text-slate-450 italic">
                    Illustrative estimate — actual results vary by industry, offer, audience and conversion rate. We do not guarantee returns.
                  </p>
                </div>
              </div>
            )}
          </CardContent>
        </Card>
      </Container>
    </section>
  );
}
